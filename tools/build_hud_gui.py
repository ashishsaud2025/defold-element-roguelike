"""Writes main/hud.gui from the declarative node manifest in tools/hud_nodes.py.

Usage:
  python tools/build_hud_gui.py --import   # one-off bootstrap: parse main/hud.gui and
                                           # regenerate tools/hud_nodes.py
  python tools/build_hud_gui.py            # emit main/hud.gui from the manifest
  python tools/build_hud_gui.py --check    # exit 0 and print the node count if the
                                           # file matches the manifest; 1 otherwise

The emitted file carries the authored node set only. gui.* positions are applied at
runtime by main/hud.gui_script (pos_rect / pos_text from src/ui/layout.lua), so the
emitted positions are all (0,0) — exactly as authored.
"""
import re
import sys

TARGET = "main/hud.gui"
MANIFEST = "tools/hud_nodes.py"

HEADER = '''# Declarative manifest of every authored node in main/hud.gui.
# Generated by tools/build_hud_gui.py --import; hand-edit to add/remove nodes.
# kind: "box" (TYPE_BOX, has a size + ui/ texture) or "text" (TYPE_TEXT, font: "text").
# Node ids are referenced from main/hud.gui_script; keep them in sync.
NODES = [
'''

FOOTER = "]\n"


def parse_target(src):
    nodes = []
    for block in re.findall(r"nodes \{(.*?)\n\}", src, re.S):
        entry = {}
        entry["id"] = re.search(r'id: "([^"]+)"', block).group(1)
        type_m = re.search(r"type: TYPE_(BOX|TEXT)", block)
        entry["kind"] = "box" if type_m.group(1) == "BOX" else "text"
        size_m = re.search(r"size \{ x: ([-0-9.]+) y: ([-0-9.]+) \}", block)
        pos_m = re.search(r"position \{ x: ([-0-9.]+) y: ([-0-9.]+) \}", block)
        if size_m:
            entry["size"] = (float(size_m.group(1)), float(size_m.group(2)))
        else:
            entry["size"] = None
        if pos_m:
            entry["pos"] = (float(pos_m.group(1)), float(pos_m.group(2)))
        else:
            entry["pos"] = (0.0, 0.0)
        if entry["kind"] == "box":
            texture_m = re.search(r'texture: "([^"]+)"', block)
            entry["texture"] = texture_m.group(1)
        else:
            entry["font"] = "text"
            text_m = re.search(r'text: "((?:[^"\\]|\\.)*)"', block)
            entry["text"] = text_m.group(1) if text_m else ""
        nodes.append(entry)
    return nodes


def format_manifest(nodes):
    lines = [HEADER]
    for n in nodes:
        if n["kind"] == "box":
            lines.append('    {"id": %r, "kind": "box", "size": %r, "texture": %r, "pos": %r},\n'
                         % (n["id"], n["size"], n["texture"], n["pos"]))
        else:
            if n["text"] and '"' in n["text"]:
                raise ValueError("text node %s: quote inside text is not handled" % n["id"])
            lines.append('    {"id": %r, "kind": "text", "text": %r, "pos": %r},\n'
                         % (n["id"], n["text"], n["pos"]))
    lines.append(FOOTER)
    return "".join(lines)


def load_manifest():
    ns = {}
    exec(open(MANIFEST, encoding="utf-8").read(), ns)
    nodes = []
    for n in ns["NODES"]:
        e = dict(n)
        e["kind"] = n["kind"]
        e["id"] = n["id"]
        e["pos"] = tuple(n.get("pos", (0.0, 0.0)))
        e["size"] = tuple(n["size"]) if n.get("size") else None
        nodes.append(e)
    return nodes


def fmt_num(v):
    s = ("%g" % v)
    # match the authored style: integer-valued floats keep a single decimal ("960.0")
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s


def emit(nodes):
    out = []
    out.append('script: "/main/hud.gui_script"\n\n')
    out.append('fonts {\n  name: "text"\n  font: "/assets/fonts/cascadia.font"\n}\n\n')
    out.append('textures {\n  name: "ui"\n  texture: "/assets/art/shapes.atlas"\n}\n\n')
    for n in nodes:
        out.append("nodes {\n")
        out.append('  position { x: %s y: %s }\n' % (fmt_num(n["pos"][0]), fmt_num(n["pos"][1])))
        if n["kind"] == "box":
            out.append("  size { x: %s y: %s }\n" % (fmt_num(n["size"][0]), fmt_num(n["size"][1])))
            out.append("  type: TYPE_BOX\n")
            out.append('  texture: "%s"\n' % n["texture"])
        else:
            out.append("  type: TYPE_TEXT\n")
            out.append('  text: "%s"\n' % n["text"])
            out.append('  font: "text"\n')
        out.append('  id: "%s"\n' % n["id"])
        if n["kind"] == "box":
            out.append('  layer: "graphics"\n')
        else:
            out.append('  layer: "text"\n')
        out.append("  inherit_alpha: true\n")
        out.append("}\n\n")
    out.append('layers { name: "graphics" }\n')
    out.append('layers { name: "text" }\n\n')
    out.append('material: "/builtins/materials/gui.material"\n')
    out.append('adjust_reference: ADJUST_REFERENCE_PARENT\n')
    return "".join(out)


def main():
    src = open(TARGET, encoding="utf-8").read()
    if "--import" in sys.argv:
        nodes = parse_target(src)
        with open(MANIFEST, "w", encoding="utf-8", newline="") as f:
            f.write(format_manifest(nodes))
        print("wrote %s: %d nodes" % (MANIFEST, len(nodes)))
        return 0
    nodes = load_manifest()
    emitted = emit(nodes)
    if "--check" in sys.argv:
        current = open(TARGET, encoding="utf-8").read()
        if emitted == current:
            print("%d nodes, manifest matches main/hud.gui" % len(nodes))
            return 0
        import difflib
        diff = list(difflib.unified_diff(current.splitlines(), emitted.splitlines(),
                                         "main/hud.gui", "manifest", lineterm=""))
        print("MISMATCH: main/hud.gui differs from the manifest (%d lines of diff):" % len(diff))
        for line in diff[:40]:
            print(line)
        return 1
    # Normalise the target file via a byte-safe write (never Set-Content/Out-File).
    with open(TARGET, "w", encoding="utf-8", newline="") as f:
        f.write(emitted)
    print("wrote %s: %d nodes" % (TARGET, len(nodes)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
