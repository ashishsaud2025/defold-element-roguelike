#!/usr/bin/env python3
"""Write .sound resources and main/sfx.go from the files in assets/sfx/ and assets/music/.

    python tools/add_sounds.py

For every `<id>.ogg` or `<id>.wav` it writes `<id>.sound` next to the file (prefers .ogg
when both exist) and regenerates `main/sfx.go` with one component per id. The loop flag
and bus come from assets/sfx/SFX_MAP.md (generated by tools/make_sfx.py). Idempotent:
unchanged files are not rewritten, and it prints what changed.

Addressing: the sfx game object is `sfx` in main/main.collection, so components are
`/sfx#<id>` and the code plays `sound.play("/sfx#" .. id, props)`.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SFX_DIR = ROOT / "assets" / "sfx"
MUSIC_DIR = ROOT / "assets" / "music"
MAP_PATH = SFX_DIR / "SFX_MAP.md"
GO_PATH = ROOT / "main" / "sfx.go"

AUDIO_EXT = (".ogg", ".wav")


def read_map():
    """id -> {bus, loop} from the Markdown table."""
    out = {}
    if not MAP_PATH.exists():
        return out
    for line in MAP_PATH.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        parts = [p.strip() for p in line.strip().strip("|").split("|")]
        if len(parts) < 7:
            continue
        sid = parts[0].strip("`")
        bus = parts[4].strip("`").lower()
        loop = parts[5].lower() == "yes"
        if bus not in ("sfx", "music"):
            bus = "sfx"
        out[sid] = {"bus": bus, "loop": loop}
    return out


def scan_audio():
    """id -> (path, bus, extension). Prefers .ogg over .wav."""
    found = {}
    for folder, bus in ((SFX_DIR, "sfx"), (MUSIC_DIR, "music")):
        if not folder.is_dir():
            continue
        for p in sorted(folder.iterdir()):
            if p.suffix.lower() not in AUDIO_EXT:
                continue
            sid = p.stem
            ext = p.suffix.lower()
            prev = found.get(sid)
            if prev is None or (ext == ".ogg" and prev[2] != ".ogg"):
                found[sid] = (p, bus, ext)
    return found


def sound_text(path, loop, bus):
    rel = "/" + path.relative_to(ROOT).as_posix()
    return (
        'sound: "%s"\n'
        "looping: %d\n"
        "loopcount: 0\n"
        'group: "%s"\n'
        "gain: 1.0\n"
        "pan: 0.0\n"
        "speed: 1.0\n" % (rel, 1 if loop else 0, bus)
    )


def go_text(ids):
    lines = []
    for sid in ids:
        lines.append("components {\n")
        lines.append('  id: "%s"\n' % sid)
        # The .sound file lives next to the source audio it was generated from.
        lines.append('  component: "%s"\n' % SOUND_COMPONENT[sid])
        lines.append("}\n")
    return "".join(lines)


SOUND_COMPONENT = {}


def write_if_changed(path, text, changed):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    changed.append(path.relative_to(ROOT).as_posix())
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report what would change, write nothing")
    args = ap.parse_args()

    meta = read_map()
    audio = scan_audio()
    changed = []
    missing_meta = []

    ids = sorted(audio)
    for sid in ids:
        path, bus, _ext = audio[sid]
        m = meta.get(sid)
        if m is None:
            missing_meta.append(sid)
        loop = m["loop"] if m else False
        if m and m["bus"] != bus:
            bus = m["bus"]
        text = sound_text(path, loop, bus)
        sound_path = path.with_suffix(".sound")
        SOUND_COMPONENT[sid] = "/" + sound_path.relative_to(ROOT).as_posix()
        if not args.check:
            write_if_changed(sound_path, text, changed)

    # Remove generated .sound files whose source audio disappeared (never touch others).
    stale = []
    old_ids = set()
    if GO_PATH.exists():
        for m in re.finditer(r'component: "([^"]+\.sound)"', GO_PATH.read_text(encoding="utf-8")):
            old_ids.add(m.group(1))
    for snd in old_ids:
        p = ROOT / snd.lstrip("/")
        if p.exists() and p.stem not in audio:
            stale.append(p.relative_to(ROOT).as_posix())
            if not args.check:
                p.unlink()
                changed.append(p.relative_to(ROOT).as_posix() + " (removed)")

    if not args.check:
        write_if_changed(GO_PATH, go_text(ids), changed)

    print("audio files : %d" % len(audio))
    print("sound comps : %d" % len(SOUND_COMPONENT))
    if changed:
        print("changed:")
        for c in changed:
            print("  " + c)
    else:
        print("changed     : nothing (already in sync)")
    if stale:
        print("stale sound resources: %s" % ", ".join(stale))
    if missing_meta:
        print("WARNING: no SFX_MAP.md row (defaulted to bus=sfx, loop=no): %s" % ", ".join(missing_meta))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
